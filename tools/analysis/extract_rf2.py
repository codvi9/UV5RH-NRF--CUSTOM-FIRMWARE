import re
p = "baofeng-uv5rh-fw/_mod/UV-5RM-Radio-Mod-main/UV-5RM Custom Firmware/firmware-source/src/drivers/fd6818b.rs"
src = open(p, encoding="utf-8").read()
consts = {}
for m in re.finditer(r"const (\w+): u(?:8|16) = (0x[0-9A-Fa-f]+);", src):
    consts[m.group(1)] = int(m.group(2), 16)
def val(t):
    t = t.strip()
    if t in consts: return consts[t]
    if t.startswith("0x"): return int(t, 16)
    return None
i = src.index("pub fn init(&mut self")
j = len(src)
body = src[i:j]
rows, skipped, in_loop = [], [], False
for line in body.split("\n"):
    s = line.strip()
    if s.startswith("for ") or s.startswith("while "):
        in_loop = True; continue
    if in_loop and s.startswith("}"):
        in_loop = False; continue
    m = re.match(r"self\.write_reg\(syst, (\w+), (.+?)\);", s)
    if m and not in_loop:
        a = val(m.group(1)); v = val(m.group(2))
        if a is None or v is None: skipped.append(s[:70]); continue
        rows.append((a, v))
print("rows:", len(rows), "skipped:", len(skipped))
print("tail rows:", rows[-10:])
seen = [a for a, _ in rows]
print("regs:", " ".join("0x%02X" % a for a in seen))
hdr = ["/* generated by tools/extract_rf.py from fd6818b.rs init() */",
       "#pragma once", "#include <stdint.h>",
       "static const uint16_t RF_INIT_TBL[][2] = {"]
for a, v in rows: hdr.append("  {0x%02X, 0x%04X}," % (a, v))
hdr.append("};"); hdr.append("#define RF_INIT_COUNT %d" % len(rows))
open("baofeng-uv5rh-fw/fw/rf_init.h", "w").write("\n".join(hdr) + "\n")
print("wrote rf_init.h")
