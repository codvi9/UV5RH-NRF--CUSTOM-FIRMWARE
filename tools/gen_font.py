CHARS = list(GLYPHS.keys())
rows = {c: GLYPHS[c].split() for c in CHARS}
# column-major: for each of 5 columns, bits 0..6 = rows top..bottom
data = []
for c in CHARS:
    for col in range(5):
        b = 0
        for row in range(7):
            if rows[c][row][col] == "1":
                b |= 1 << row
        data.append(b)
lines = []
lines.append("/* generated by tools/gen_font.py - 5x7 column-major, bit0=top */")
lines.append("#define FONT_FIRST 32")
lines.append("#define FONT_LAST %d" % (FONT_LAST if False else 0))
out = ["/* generated by tools/gen_font.py */", "#pragma once", "#include <stdint.h>", ""]
out.append("static const char FONT_CHARS[] = \"\";")
for c in CHARS:
    out.append("/* %s */" % (c if c != ' ' else 'space'))
out_tbl = "static const uint8_t FONT_5X7[][5] = {\n"
for c in CHARS:
    cols = []
    for col in range(5):
        b = 0
        for row in range(7):
            if rows[c][row][col] == "1":
                b |= 1 << row
        cols.append("0x%02X" % b)
    out_tbl += "  {%s}, /* %s */\n" % (", ".join(cols), c if c != " " else "sp")
out_tbl += "};\n"
out_tbl += "static const char FONT_MAP[] = \"%s\";\n" % ("".join(CHARS).replace('\\','\\\\').replace('"','\\"'))
open("baofeng-uv5rh-fw/fw/font.h", "w").write("\n".join(out) + "\n" + out_tbl)
print("glyphs:", len(CHARS))
print("table bytes:", len(CHARS)*5)
